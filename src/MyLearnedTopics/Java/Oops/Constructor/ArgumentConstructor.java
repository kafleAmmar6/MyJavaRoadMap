package MyLearnedTopics.Java.Oops.Constructor;

public class ArgumentConstructor {
    public String thirdUserName;
    public String thirdUserAddress;
    public boolean thirdUserAlive;
    public int thirdUserAge;

    public ArgumentConstructor(String thirdUserName, String thirdUserAddress, boolean thirdUserAlive, int thirdUserAge) {
        this.thirdUserName = thirdUserName;
        this.thirdUserAddress = thirdUserAddress;
        this.thirdUserAlive = thirdUserAlive;
        this.thirdUserAge = thirdUserAge;
    }
}
